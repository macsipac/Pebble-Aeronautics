 //! Generates `ALL_COMPONENTS` (name -> `DataComponent`) from the `data-component` enum of the Pumpkin
//! plugin API that is actually being compiled against, so a nightly that adds, removes or reorders
//! components can never break the build of `plugin.rs`.
//!
//! WIT file lookup order:
//!   1. `$PUMPKIN_WIT_DIR/data-components.wit` (manual override)
//!   2. next to the `pumpkin-plugin-api` crate found via `cargo metadata`
//!      (`../pumpkin-plugin-wit/v0.1/`, exactly the directory the API's wit-bindgen reads)
//!   3. `data-components.wit` in this crate's root (a snapshot; used only if 1 and 2 fail)
use std::{env, fs, path::{Path, PathBuf}, process::Command};

const WIT_FILE: &str = "data-components.wit";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={WIT_FILE}");
    println!("cargo:rerun-if-env-changed=PUMPKIN_WIT_DIR");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let candidates = [from_env(), from_cargo_metadata(&manifest_dir), Some(manifest_dir.join(WIT_FILE))];

    let mut names = Vec::new();
    for path in candidates.into_iter().flatten() {
        if let Ok(text) = fs::read_to_string(&path) {
            let parsed = parse_enum(&text);
            if !parsed.is_empty() {
                println!("cargo:rerun-if-changed={}", path.display());
                println!("cargo:warning=physics: {} data components read from {}", parsed.len(), path.display());
                names = parsed;
                break;
            }
        }
    }

    // Never fail the build: with an empty table the plugin still works, it just cannot save/restore
    // item components (chest contents come back without enchantments, names, ...).
    if names.is_empty() {
        println!("cargo:warning=physics: data-components.wit not found; item components will not be persisted");
    }

    let mut out = String::from("// @generated by build.rs\nconst ALL_COMPONENTS: &[(&str, DataComponent)] = &[\n");
    for n in &names {
        out.push_str(&format!("    ({:?}, DataComponent::{}),\n", n, upper_camel(n)));
    }
    out.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("components_gen.rs"), out).unwrap();
}

fn from_env() -> Option<PathBuf> {
    env::var("PUMPKIN_WIT_DIR").ok().map(|d| Path::new(&d).join(WIT_FILE))
}

/// Finds `pumpkin-plugin-api` in `cargo metadata` and returns the WIT file next to it. The JSON is
/// scanned by hand to avoid a build-dependency.
fn from_cargo_metadata(manifest_dir: &Path) -> Option<PathBuf> {
    let cargo = env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let out = Command::new(cargo)
        .args(["metadata", "--format-version", "1", "--offline", "--manifest-path"])
        .arg(manifest_dir.join("Cargo.toml"))
        .output()
        .ok()?;
    if !out.status.success() { return None; }
    let json = String::from_utf8(out.stdout).ok()?;
    // A package entry has `"name":"..","version":..`; dependency entries have `"name":"..","source":..`.
    let at = json.find("\"name\":\"pumpkin-plugin-api\",\"version\"")?;
    let rest = &json[at..];
    let key = "\"manifest_path\":\"";
    let m = rest.find(key)? + key.len();
    let raw = &rest[m..m + rest[m..].find('"')?];
    let manifest = PathBuf::from(raw.replace("\\\\", "\\"));
    let api_dir = manifest.parent()?;
    [
        api_dir.join("../pumpkin-plugin-wit/v0.1").join(WIT_FILE),
        api_dir.join("wit").join(WIT_FILE),
    ]
    .into_iter()
    .find(|p| p.exists())
}

/// Names inside `enum data-component { ... }`, in declaration order.
fn parse_enum(text: &str) -> Vec<String> {
    let Some(i) = text.find("enum data-component") else { return Vec::new() };
    let Some(open) = text[i..].find('{') else { return Vec::new() };
    let body = &text[i + open + 1..];
    let Some(close) = body.find('}') else { return Vec::new() };
    body[..close]
        .lines()
        .map(|l| l.split("//").next().unwrap_or("").trim())
        .flat_map(|l| l.split(','))
        .map(str::trim)
        .filter(|n| !n.is_empty() && n.chars().all(|c| c.is_ascii_alphanumeric() || c == '-'))
        .map(str::to_string)
        .collect()
}

/// `can-place-on` -> `CanPlaceOn` (wit-bindgen's naming for enum cases).
fn upper_camel(kebab: &str) -> String {
    kebab
        .split('-')
        .map(|w| {
            let mut c = w.chars();
            c.next().map(|f| f.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
        })
        .collect()
}
